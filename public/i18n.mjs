export const KEYS = Object.keys(DICT);
export const has = (key) => Object.prototype.hasOwnProperty.call(DICT, key);

/** 取当前语言的文案；缺条目回退中文。vars 做 {name} 占位替换。 */
export function t(key, vars) {
  const row = DICT[key];
  let s;
  if (!row) { console.warn('[i18n] missing key:', key); s = key; }
  else s = row[langIndex()] ?? row[0];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

/** 把 index.html 里带 data-i18n / data-i18n-title / data-i18n-ph 的静态节点刷成当前语言。 */
export function applyStatic(root = document) {
  document.documentElement.lang = lang();
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll('[data-i18n-title]')) el.title = t(el.dataset.i18nTitle);
  for (const el of root.querySelectorAll('[data-i18n-ph]')) el.placeholder = t(el.dataset.i18nPh);
  if (document.title) document.title = `AI Dev Platform · ${t('app.title')}`;
}

/** 本语言包是否三语齐全（自检用）。 */
export function audit() {
  const bad = [];
  for (const [k, row] of Object.entries(DICT)) {
    if (!Array.isArray(row) || row.length !== LANGS.length) bad.push(`${k}: entry count ${row?.length} != ${LANGS.length}`);
    else row.forEach((s, i) => { if (typeof s !== 'string' || !s.length) bad.push(`${k}: ${LANGS[i].code} is empty`); });
  }
  return bad;
}
